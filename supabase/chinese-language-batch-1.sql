    node_id, question_type, question_text, options,
    difficulty, source_type, status
  )
  select
    n.id, 'multiple_choice', p.question_text, p.options,
    p.difficulty, 'teacher', 'published'
  from payload p
  join public.curriculum_nodes n on n.code = p.node_code
  where not exists (
    select 1
    from public.questions existing
    where existing.node_id = n.id
      and existing.question_text = p.question_text
  )
  returning id, node_id, question_text
)
insert into public.question_answer_keys (
  question_id, correct_answer, explanation, hint
)
select
  i.id,
  to_jsonb(p.correct_answer),
  p.explanation,
  p.hint
from inserted i
join public.curriculum_nodes n on n.id = i.node_id
join payload p
  on p.node_code = n.code
 and p.question_text = i.question_text
on conflict (question_id) do update
set correct_answer = excluded.correct_answer,
    explanation = excluded.explanation,
    hint = excluded.hint;

